 # 13.6 Summary:
# Python modules are files containing Python definitions and statements, often defining functions, classes, and variables. 
# Python libraries are collections of related modules containing bundles of code that can be used repeatedly in different programs. 
# Python packages are directories of a collection of modules, used to manage and organize modules and submodules.

# Key points:


# Python modules are files containing Python definitions and statements.
# Python libraries are collections of related modules.

# Python packages are directories of a collection of modules.
# In summary, Python modules, libraries, and packages are fundamental constructs that facilitate code modularization, reusability, and organization.









# 13.7 Lesson Quiz :

# 1) What is the purpose of the Netmiko package in Python?

# Answer ) Netmiko is a multi-vendor library used to simplify Paramiko SSH connections to network devices


# 2) What is the purpose of creating a Python module?

# Answer ) Creating a Python module allows for code reuse across multiple scripts, which improves code organization and readability



# 3) What is the purpose of using the 'as' keyword when importing a module in Python?

# Answer ) A module can be renamed upon import using the 'as' keyword, making subsequent calls to the module’s functions more concise


# 4) What does the dir() function do when a module is passed as an argument in Python?

# Answer ) When a module is passed as an argument to dir(), it returns a list of the module’s attributes, including its functions


# 5) What is the advantage of using the from ... import ... statement in Python?

# Answer ) It allows for importing only the necessary functions or classes, making the code more efficient


# 6) What is the purpose of the Python Standard Library?

# Answer ) It provides a wide range of functionalities, including mathematical operations, file I/O, system calls, and even Internet protocols

# 7) What happens when you use the pip uninstall package_name command in Python?

# Answer ) It removes a package from the system, and it will no longer be available for import in Python scripts